        //Method to encypt the System Key
        public static string Encryption(string Text_To_Encrypt)
        {
            try
            {
                string TextToEncrypt = Text_To_Encrypt;
                //Reverse the string
                char[] Reverse_Text_To_Encrypt = Text_To_Encrypt.ToCharArray();
                Array.Reverse(Reverse_Text_To_Encrypt);
                TextToEncrypt = new string(Reverse_Text_To_Encrypt);
                //Find the length of string 
                int KeyLength = Convert.ToUInt16(TextToEncrypt.Length.ToString().Substring(0, 1));
                //ASCII Encoding
                Text_To_Encrypt = string.Concat(TextToEncrypt.Select(c => (char)(c + KeyLength))) + KeyLength;
                //Get the KEY IV paire
                var Key_IV = KeyIV.ElementAt(new Random().Next(10));
                char EncryptChar = (char)(KeyIV.ToList().IndexOf(Key_IV) + '9');
                //Convert text By Key paire values
                byte[] EncryptedTextByte;
                using (AesManaged ObjAesManaged = new AesManaged())
                {
                    ICryptoTransform Encryptor = ObjAesManaged.CreateEncryptor(Encoding.ASCII.GetBytes(Key_IV.Key), Encoding.ASCII.GetBytes(Key_IV.Value));
                    using (MemoryStream ObjMemoryStream = new MemoryStream())
                    {
                        using (CryptoStream ObjCryptoStream = new CryptoStream(ObjMemoryStream, Encryptor, CryptoStreamMode.Write))
                        {
                            using (StreamWriter ObjStreamWriter = new StreamWriter(ObjCryptoStream))
                                ObjStreamWriter.Write(Text_To_Encrypt);
                            EncryptedTextByte = ObjMemoryStream.ToArray();
                        }
                    }
                }
                return Convert.ToBase64String(EncryptedTextByte) + EncryptChar;
            }
            catch
            {
                return null;
            }
        }

