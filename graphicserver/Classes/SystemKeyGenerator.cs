        //Getting Active Ip Address
        static string GetActiveIpAddress()
        {
            string alladresses = "";
            foreach (NetworkInterface ni in NetworkInterface.GetAllNetworkInterfaces())
            {
                if (ni.OperationalStatus == OperationalStatus.Up &&
                    ni.NetworkInterfaceType != NetworkInterfaceType.Loopback)
                {
                    foreach (UnicastIPAddressInformation ip in ni.GetIPProperties().UnicastAddresses)
                    {
                        if (ip.Address.AddressFamily == AddressFamily.InterNetwork &&
                            !IPAddress.IsLoopback(ip.Address))
                        {
                            alladresses += ip.Address.ToString() + " |";
                        }
                    }

                }
            }
            alladresses = alladresses.TrimEnd('|');
            return alladresses;
        }

        //Getting CPU Id 
        public static string GetCpuId()
        {
            try
            {
                using (var searcher = new ManagementObjectSearcher("SELECT ProcessorId FROM Win32_Processor"))
                {
                    foreach (ManagementObject mo in searcher.Get())
                    {
                        return mo["ProcessorId"]?.ToString().Trim();
                    }
                }
            }
            catch
            {
            }
            return string.Empty;
        }

        //Getting motherboard serial number
        static string GetMotherboardSerial()
        {
            try
            {
                using (var searcher = new ManagementObjectSearcher("SELECT SerialNumber FROM Win32_BaseBoard"))
                {
                    foreach (ManagementObject mo in searcher.Get())
                    {
                        return mo["SerialNumber"]?.ToString().Trim();
                    }
                }
            }
            catch
            {
            }
            return string.Empty;
        }

